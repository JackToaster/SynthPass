void test_id_verify_valid(void) {
    PM_Identity id = {0};
    memcpy(id.pub_key, test_client_pub, PUB_KEY_SIZE);

    uint8_t sig[SIGNATURE_SIZE];
    memcpy(sig, test_client_sig, SIGNATURE_SIZE);

    uint8_t result = id_verify(&id, sig, (const uint8_t*)test_message, (int)strlen(test_message));

    TEST_ASSERT_NOT_EQUAL(0, result);
}

void test_id_verify_invalid(void) {
    PM_Identity id = {0};
    memcpy(id.pub_key, test_client_pub, PUB_KEY_SIZE);

    uint8_t sig[SIGNATURE_SIZE];
    memcpy(sig, test_client_sig, SIGNATURE_SIZE);
    sig[0] ^= 0xFF; // corrupt the signature

    uint8_t result = id_verify(&id, sig, (const uint8_t*)test_message, (int)strlen(test_message));

    TEST_ASSERT_EQUAL_UINT8(0, result);
}

void test_local_id_sign(void) {
    PM_LocalIdentity id = {0};
    memcpy(id.pub_key, test_client_pub, PUB_KEY_SIZE);
    memcpy(id.prv_key, test_client_prv, PRV_KEY_SIZE);

    uint8_t sig[SIGNATURE_SIZE];
    memset(sig, 0, sizeof(sig));

    local_id_sign(&id, sig, (uint8_t*)test_message, (uint16_t)strlen(test_message));

    TEST_ASSERT_EQUAL_UINT8_ARRAY(test_client_sig, sig, SIGNATURE_SIZE);
}

void test_local_id_calc_shared_secrt(void) {
    PM_LocalIdentity id = {0};
    memcpy(id.pub_key, test_client_pub, PUB_KEY_SIZE);
    memcpy(id.prv_key, test_client_prv, PRV_KEY_SIZE);

    PM_Identity other = {0};
    memcpy(other.pub_key, other_pub, PUB_KEY_SIZE);

    uint8_t secret[PUB_KEY_SIZE];
    memset(secret, 0, sizeof(secret));

    local_id_calc_shared_secrt(&id, secret, &other);

    TEST_ASSERT_EQUAL_UINT8_ARRAY(expected_shared_secret, secret, PUB_KEY_SIZE);
}

void test_local_id_validate_private_key_valid(void) {
    uint8_t prv[PRV_KEY_SIZE];
    memcpy(prv, test_client_prv, PRV_KEY_SIZE);

    uint8_t result = local_id_validate_private_key(prv);

    TEST_ASSERT_NOT_EQUAL(0, result);
}

void test_local_id_validate_private_key_invalid(void) {
    uint8_t prv[PRV_KEY_SIZE];
    memcpy(prv, weak_prv, PRV_KEY_SIZE);

    uint8_t result = local_id_validate_private_key(prv);

    TEST_ASSERT_EQUAL_UINT8(0, result);
}

